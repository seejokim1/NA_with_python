# section_10_02_nonlinear_shooting_method.py
# (10.2) 비선형 Shooting Method
# Blasius 방정식 예제

import numpy as np
from scipy.integrate import solve_ivp
import matplotlib.pyplot as plt

# ------------------------------------------------------------------
# Blasius 방정식
# y[0] = f
# y[1] = f'
# y[2] = f''
# f''' + f f'' = 0
# ------------------------------------------------------------------
def blasius(eta, y):
    return [y[1], y[2], -y[0] * y[2]]

# ------------------------------------------------------------------
# 목표 경계 조건
# f'(∞) = 1
# ------------------------------------------------------------------
target = 1.0

# ------------------------------------------------------------------
# 초기 추정값 (f''(0))
# ------------------------------------------------------------------
guesses = [1.0, 0.1]
results = []

eta_span = (0.0, 10.0)
eta_eval = np.linspace(0.0, 10.0, 200)

# ------------------------------------------------------------------
# 첫 번째 추정값
# ------------------------------------------------------------------
sol1 = solve_ivp(
    blasius, eta_span,
    [0.0, 0.0, guesses[0]],
    t_eval=eta_eval
)
results.append(sol1.y[1, -1])

# ------------------------------------------------------------------
# 두 번째 추정값
# ------------------------------------------------------------------
sol2 = solve_ivp(
    blasius, eta_span,
    [0.0, 0.0, guesses[1]],
    t_eval=eta_eval
)
results.append(sol2.y[1, -1])

# ------------------------------------------------------------------
# 선형 보간(Secant method)으로 새로운 추정값 계산
# ------------------------------------------------------------------
m = (guesses[0] - guesses[1]) / (results[0] - results[1])
guess3 = guesses[1] + m * (target - results[1])

# ------------------------------------------------------------------
# 세 번째 추정값 계산
# ------------------------------------------------------------------
sol3 = solve_ivp(
    blasius, eta_span,
    [0.0, 0.0, guess3],
    t_eval=eta_eval
)
result3 = sol3.y[1, -1]

# ------------------------------------------------------------------
# 결과 출력
# ------------------------------------------------------------------
print("비선형 Shooting Method (Blasius 방정식)")
print(f"추정값 1: f''(0) = {guesses[0]:.4f}, f'(∞) = {results[0]:.4f}")
print(f"추정값 2: f''(0) = {guesses[1]:.4f}, f'(∞) = {results[1]:.4f}")
print(f"추정값 3: f''(0) = {guess3:.4f}, f'(∞) = {result3:.4f}")
print(f"목표값: f'(∞) = {target:.3f}")

