# (7.2.3) 행렬식을 이용한 m 차 다항식 근사 소스코드

import numpy as np
import matplotlib.pyplot as plt

# ------------------------------------------------------------------
# 데이터 생성
# y = -(theta0 + theta1*x + theta2*x^2 + noise)
# ------------------------------------------------------------------
n = 100
x = -5 + 15 * np.random.rand(n, 1)
noise = 10 * np.random.randn(n, 1)

y = -(10 + 1 * x + 2 * x**2 + noise)

# ------------------------------------------------------------------
# 설계 행렬 A 구성 (2차 다항식)
# A = [1, x, x^2]
# ------------------------------------------------------------------
A = np.hstack([x**0, x, x**2])
A = np.asmatrix(A)

# ------------------------------------------------------------------
# 최소자승법 (정규방정식)
# theta = (A^T A)^(-1) A^T y
# ------------------------------------------------------------------
theta = (A.T * A).I * A.T * y

print("회귀 계수 theta:")
print(theta)

# ------------------------------------------------------------------
# 근사 곡선 계산
# ------------------------------------------------------------------
xp = np.linspace(np.min(x), np.max(x), 200)
yp = (
    theta[0, 0]
    + theta[1, 0] * xp
    + theta[2, 0] * xp**2
)

# ------------------------------------------------------------------
# 결과 시각화
# ------------------------------------------------------------------
plt.figure(figsize=(10, 8))

plt.plot(
    x, y,
    'o', markersize=4, label='실제 데이터'
)

plt.plot(
    xp, yp,
    'r', linewidth=2, label='2차 다항식 근사'
)

plt.title('행렬식을 이용한 다항식 근사 (최소자승법)', fontsize=15)
plt.xlabel('x', fontsize=15)
plt.ylabel('y', fontsize=15)
plt.xlim([np.min(x), np.max(x)])
plt.grid(alpha=0.3)
plt.legend(fontsize=13)

plt.show()
