# 네 개의 점 좌표 입력
x1, y1 = input("첫번째 좌표를 입력해주세요 : ").split()
x1 = float(x1); y1 = float(y1)

x2, y2 = input("두번째 좌표를 입력해주세요 : ").split()
x2 = float(x2); y2 = float(y2)

x3, y3 = input("세번째 좌표를 입력해주세요 : ").split()
x3 = float(x3); y3 = float(y3)

x4, y4 = input("네번째 좌표를 입력해주세요 : ").split()
x4 = float(x4); y4 = float(y4)

# 1차 가우스 적분용 자코비안
J1 = (1/8) * (((x1 - x3) * (y2 - y4)) - ((x2 - x4) * (y1 - y3)))

# 2차 가우스 적분용 자코비안 (4개 적분점)
J2_1 = (1/8) * (((x1 - x3) * (y2 - y4)) - ((x2 - x4) * (y1 - y3))) \
    - (1/8) * (0.5774) * (((x1 - x2) * (y3 - y4)) - ((y1 - y2) * (x3 - x4))) \
    - (1/8) * (0.5774) * (((x1 - x4) * (y2 - y3)) - ((y1 - y4) * (x2 - x3)))

J2_2 = (1/8) * (((x1 - x3) * (y2 - y4)) - ((x2 - x4) * (y1 - y3))) \
    - (1/8) * (0.5774) * (((x1 - x2) * (y3 - y4)) - ((y1 - y2) * (x3 - x4))) \
    - (1/8) * (-0.5774) * (((x1 - x4) * (y2 - y3)) - ((y1 - y4) * (x2 - x3)))

J2_3 = (1/8) * (((x1 - x3) * (y2 - y4)) - ((x2 - x4) * (y1 - y3))) \
    - (1/8) * (-0.5774) * (((x1 - x2) * (y3 - y4)) - ((y1 - y2) * (x3 - x4))) \
    - (1/8) * (0.5774) * (((x1 - x4) * (y2 - y3)) - ((y1 - y4) * (x2 - x3)))

J2_4 = (1/8) * (((x1 - x3) * (y2 - y4)) - ((x2 - x4) * (y1 - y3))) \
    - (1/8) * (-0.5774) * (((x1 - x2) * (y3 - y4)) - ((y1 - y2) * (x3 - x4))) \
    - (1/8) * (-0.5774) * (((x1 - x4) * (y2 - y3)) - ((y1 - y4) * (x2 - x3)))

# 가우스 가중치
g1w1 = 2
g2w1 = 1
g2w2 = 1

# 1차 가우스 적분 결과
print('GP1_Gauss :', J1 * (g1w1 + g1w1))

# 2차 가우스 적분 결과
print('GP2_Gauss :',
      J2_1 * (g2w1 * g2w1) +
      J2_2 * (g2w1 * g2w2) +
      J2_3 * (g2w2 * g2w1) +
      J2_4 * (g2w2 * g2w2))
