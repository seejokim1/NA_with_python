# ------------------------------------------------------------------
# 미분 방정식 정의
# y1' = y2
# y2' = (-c*y2 - k*y1 + A sin(ωt)) / m
# ------------------------------------------------------------------
def f1(y1, y2, time):
    return y2

def f2(y1, y2, time):
    return (-c * y2 - k * y1 + Amp * np.sin(omega * time)) / m

# ------------------------------------------------------------------
# Runge-Kutta 4차 방법
# ------------------------------------------------------------------
def rk4(dt, y1, y2, time):
    k1 = dt * np.array([f1(y1, y2, time),
                         f2(y1, y2, time)])
    k2 = dt * np.array([f1(y1 + 0.5 * k1[0], y2 + 0.5 * k1[1], time + 0.5 * dt),
                         f2(y1 + 0.5 * k1[0], y2 + 0.5 * k1[1], time + 0.5 * dt)])
    k3 = dt * np.array([f1(y1 + 0.5 * k2[0], y2 + 0.5 * k2[1], time + 0.5 * dt),
                         f2(y1 + 0.5 * k2[0], y2 + 0.5 * k2[1], time + 0.5 * dt)])
    k4 = dt * np.array([f1(y1 + k3[0], y2 + k3[1], time + dt),
                         f2(y1 + k3[0], y2 + k3[1], time + dt)])

    y_next = np.array([y1, y2]) + (k1 + 2*k2 + 2*k3 + k4) / 6.0
    return y_next[0], y_next[1]

# ------------------------------------------------------------------
# Explicit Euler 방법
# ------------------------------------------------------------------
def euler(dt, y1, y2, time):
    y1_new = y1 + dt * f1(y1, y2, time)
    y2_new = y2 + dt * f2(y1, y2, time)
    return y1_new, y2_new

